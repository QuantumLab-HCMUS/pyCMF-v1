'''
One-body downfolding (OBDF).

Dynamic correlation outside an active space is folded into the one-body part
of an active-space Hamiltonian,

    H_act = E_core + sum_tu hbar_tu a+_t a_u + 1/2 sum_tuvw (tu|vw) a+_t a+_v a_w a_u,
    hbar  = h + v_core^HF + v_ext,

where v_ext is the OBMP2 correlation potential generated by the double
excitations with at least one index outside the active space,

    v_ext = v[T] - v[T_act].

The two-electron integrals are the bare ones, so the Hamiltonian has the
structure of a CASCI Hamiltonian and can be handed to any solver (FCI, DMRG,
selected CI, VQE, ...).  Limits: if the active space spans all orbitals,
H_act is the full Hamiltonian; if it is empty, E_core is the OBMP2 energy.

Simple usage::

    >>> mp = pycmf.OBMP2(mf).run()
    >>> ham = pycmf.OBDF(mp, ncas=6, nelecas=6)
    >>> e_tot = ham.kernel()            # FCI in the active space
    >>> ham.to_fcidump('active.fcidump')

Reference:
    N. T. Le and L. N. Tran, J. Phys. Chem. A 127, 5222 (2023)
'''

import numpy
from pyscf import ao2mo, fci, lib
from pyscf.lib import logger
from pyscf.tools import fcidump

from pycmf.core import amplitudes
from pycmf.mol import bch
from pycmf.mol.obmp2 import OBMP2Base


class OBDF(lib.StreamObject):
    '''Active-space Hamiltonian downfolded with the OBMP2 correlation potential.

    Args:
        mp : converged OBMP2 or O2BMP2 object
        ncas : number of active orbitals
        nelecas : number of active electrons, int or (nalpha, nbeta)
        cas_list : indices (0-based, in the orbital order of ``mp``) of the
            active orbitals; a pair of lists for different alpha and beta
            choices.  By default the ``ncas`` orbitals around the Fermi
            level that hold ``nelecas`` electrons are taken.

    Attributes:
        fcisolver : solver with the interface of :mod:`pyscf.fci`
        nroots : number of states requested from the solver

    Saved results:
        e_core : constant of the active-space Hamiltonian (with nuclear repulsion)
        h1eff : effective one-body integrals (a pair for an unrestricted reference)
        h2eff : active two-electron integrals, (aa, ab, bb) for an unrestricted reference
        e_tot, e_cas, ci : total energy, active-space energy and CI vector(s)
    '''

    _keys = {'mol', 'mp', 'ncas', 'nelecas', 'cas_list', 'fcisolver', 'nroots',
             'e_core', 'h1eff', 'h2eff', 'e_tot', 'e_cas', 'ci', 'mo_coeff'}

    def __init__(self, mp, ncas, nelecas, cas_list=None):
        if not isinstance(mp, OBMP2Base):
            raise TypeError('OBDF needs an OBMP2 object.')
        if type(mp).get_reference is not OBMP2Base.get_reference:
            raise NotImplementedError('OBDF is defined for HF-based OBMP2/O2BMP2 only.')
        if mp.mo_energy is None:
            raise RuntimeError('Run the OBMP2 calculation first.')
        self.mp = mp
        self.mol = mp.mol
        self.verbose = mp.verbose
        self.stdout = mp.stdout
        self.max_memory = mp.max_memory
        self.ncas = ncas
        if isinstance(nelecas, (int, numpy.integer)):
            nelecb = (nelecas - self.mol.spin) // 2
            nelecas = (nelecas - nelecb, nelecb)
        self.nelecas = tuple(int(n) for n in nelecas)
        self.cas_list = cas_list
        self.restricted = mp._occ == 2
        self.fcisolver = fci.direct_spin1.FCI(self.mol) if self.restricted \
            else fci.direct_uhf.FCI(self.mol)
        self.nroots = 1

        self.mo_coeff = None
        self.e_core = None
        self.h1eff = None
        self.h2eff = None
        self.e_tot = None
        self.e_cas = None
        self.ci = None

    def _active_indices(self, nocc):
        '''Per-channel arrays of core and active orbital indices.'''
        nchan = len(nocc)
        if self.cas_list is None:
            nel = self.nelecas if nchan == 2 else (sum(self.nelecas) // 2,)
            act = []
            for s in range(nchan):
                ncore = nocc[s] - nel[s]
                if ncore < 0:
                    raise ValueError('More active electrons than electrons.')
                act.append(numpy.arange(ncore, ncore + self.ncas))
        else:
            cl = self.cas_list
            if isinstance(cl[0], (int, numpy.integer)):
                cl = [cl] * nchan
            act = [numpy.sort(numpy.asarray(c, dtype=int)) for c in cl]
        core = []
        for s in range(nchan):
            if len(act[s]) != self.ncas or len(set(act[s].tolist())) != self.ncas:
                raise ValueError('cas_list must hold ncas distinct orbitals.')
            occ = numpy.arange(nocc[s])
            core.append(numpy.setdiff1d(occ, act[s]))
        return core, act

    def build(self):
        '''Construct E_core, h1eff and h2eff.'''
        log = logger.new_logger(self)
        cput0 = (logger.process_clock(), logger.perf_counter())
        mp = self.mp
        hf = mp.get_hf()
        mo_energy, mo_coeff, nocc = mp._channels()
        nchan = len(nocc)
        core, act = self._active_indices(nocc)

        for s in range(nchan):
            inact = numpy.setdiff1d(numpy.arange(mo_energy[s].size), act[s])
            if len(inact) and len(act[s]):
                gap = abs(mo_energy[s][act[s], None] - mo_energy[s][inact]).min()
                if gap < 1e-6:
                    log.warn('An active orbital is degenerate with an inactive one '
                             '(spin channel %d): the active space is not uniquely '
                             'defined.', s)

        im = mp.build(mo_energy, mo_coeff, nocc)
        occ_act, vir_act = [], []
        for s in range(nchan):
            mask = numpy.zeros(mo_coeff[s].shape[1], dtype=bool)
            mask[act[s]] = True
            occ_act.append(mask[:nocc[s]])
            vir_act.append(mask[nocc[s]:])
        blocks_act = amplitudes.restrict_to_active(im.blocks, occ_act, vir_act)
        v_act, c0_act, _ = bch.correlation_potential(
            mp.ao2mo(), blocks_act, im.fock_hf, nocc, mp.bch_order, weight=mp._occ)
        v_ext = [v - va for v, va in zip(im.v, v_act)]
        blocks_act = im.blocks = None

        # mean field of the core electrons
        h1e = hf.get_hcore()
        dm_core = mp._pack([mp._occ * c[:, idx].dot(c[:, idx].conj().T)
                            for c, idx in zip(mo_coeff, core)])
        vhf_core = hf.get_veff(self.mol, dm_core)
        e_core = hf.energy_elec(dm_core, h1e, vhf_core)[0] + hf.energy_nuc()
        e_core += im.c0 - c0_act
        e_core += mp._occ * sum(v[idx, idx].sum() for v, idx in zip(v_ext, core))

        fock_core = mp._unpack(h1e + vhf_core)
        mo_act = [c[:, idx] for c, idx in zip(mo_coeff, act)]
        h1eff = [c.conj().T.dot(f).dot(c) + v[numpy.ix_(idx, idx)]
                 for c, f, v, idx in zip(mo_act, fock_core, v_ext, act)]

        self.mo_coeff = mp._pack(mo_act)
        self.e_core = e_core
        self.h1eff = mp._pack(h1eff)
        self.h2eff = self._ao2mo(mo_act)
        nel_ref = [int(numpy.count_nonzero(a < n)) for a, n in zip(act, nocc)]
        log.info('OBDF: ncas = %d, active occupied orbitals per channel = %s, '
                 'ncore = %s', self.ncas, nel_ref, [len(c) for c in core])
        log.info('E_core = %.15g', e_core)
        log.timer('OBDF Hamiltonian', *cput0)
        return self

    def _ao2mo(self, mo_act):
        mp = self.mp
        if mp.with_df is not None:
            def trans(*mos):
                return mp.with_df.ao2mo(mos, compact=False)
        else:
            eri = getattr(mp._scf, '_eri', None)
            if eri is None:
                eri = self.mol

            def trans(*mos):
                return ao2mo.general(eri, mos, compact=False)
        n = self.ncas
        if len(mo_act) == 1:
            c = mo_act[0]
            return trans(c, c, c, c).reshape(n, n, n, n)
        ca, cb = mo_act
        return (trans(ca, ca, ca, ca).reshape(n, n, n, n),
                trans(ca, ca, cb, cb).reshape(n, n, n, n),
                trans(cb, cb, cb, cb).reshape(n, n, n, n))

    def get_h1eff(self):
        '''Effective one-body integrals and the constant E_core.'''
        if self.h1eff is None:
            self.build()
        return self.h1eff, self.e_core

    def get_h2eff(self):
        '''Active-space two-electron integrals, chemists' notation.'''
        if self.h2eff is None:
            self.build()
        return self.h2eff

    def kernel(self, ci0=None, **kwargs):
        '''Solve the active-space problem with ``fcisolver``.

        Returns the total energy (a list if ``nroots`` > 1).
        '''
        h1, e_core = self.get_h1eff()
        h2 = self.get_h2eff()
        solver = self.fcisolver
        if self.nroots > 1:
            kwargs['nroots'] = self.nroots
        e_cas, self.ci = solver.kernel(h1, h2, self.ncas, self.nelecas, ci0=ci0, **kwargs)
        self.e_cas = e_cas
        self.e_tot = e_cas + e_core if self.nroots == 1 else numpy.asarray(e_cas) + e_core
        logger.note(self, 'E(OBDF) = %s  E_cas = %s  E_core = %.15g',
                    self.e_tot, self.e_cas, e_core)
        return self.e_tot

    def to_fcidump(self, filename, tol=1e-15, **kwargs):
        '''Write the active-space Hamiltonian in FCIDUMP format (restricted
        reference only; E_core is written as the constant term).'''
        if not self.restricted:
            raise NotImplementedError(
                'FCIDUMP needs spin-free integrals.  Use get_h1eff()/get_h2eff() '
                'for the spin-resolved Hamiltonian of an unrestricted reference.')
        h1, e_core = self.get_h1eff()
        h2 = ao2mo.restore(8, self.get_h2eff(), self.ncas)
        ms = self.nelecas[0] - self.nelecas[1]
        fcidump.from_integrals(filename, h1, h2, self.ncas, self.nelecas, nuc=e_core,
                               ms=ms, tol=tol, **kwargs)
        return filename
