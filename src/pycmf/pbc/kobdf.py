'''
One-body downfolding with k-point sampling (KOBDF), closed shell.
EXPERIMENTAL.

The k-point analogue of :mod:`pycmf.downfold.obdf`.  Dynamic correlation
outside a set of active bands is folded into the one-body part of an
active-space Hamiltonian (energies per unit cell),

    H_act = E_core + 1/Nk sum_k sum_tu hbar_tu(k) a+_tk a_uk
            + 1/(2 Nk) sum_{k1 k2 k3} sum_tuvw h2[k1,k2,k3]_tuvw a+_t,k1 a+_v,k3 a_w,k4 a_u,k2,

    hbar(k) = h(k) + v_core^HF(k) + v_ext(k),     v_ext = v[T] - v[T_act],
    h2[k1,k2,k3] = (t k1, u k2 | v k3, w k4) / Nk,

where v[T] is the correlation potential of KOBMP2 and v[T_act] the potential
generated by the double excitations within the active bands.  The
two-electron integrals are the bare ones.

The implementation is built on the modules of :class:`pycmf.pbc.KOBMP2`: the
two potentials are two calls of :func:`pycmf.pbc.kbch.correlation_potential`
(all correlated orbitals; active orbitals only), and all integrals are
assembled from the three-index tensors of :mod:`pycmf.pbc.kintegrals`,
L^Q_tu(k1, k2).  No four-index integral over the k-mesh is transformed unless
it is requested.

    >>> mp = KOBMP2(kmf).run()
    >>> ham = KOBDF(mp, ncas=8, nelecas=8)        # or mp.downfold(8, 8)
    >>> h1, e_core = ham.get_h1eff()             # (nkpts, ncas, ncas)
    >>> ham.scf()                                # mean field of H_act
    >>> ham.self_energy(nocc=1, nvir=1)
    >>> ham.quasiparticle_gap('dynamic')         # second-order gap of H_act
    >>> h1s, h2s, e0, nelec = ham.supercell()    # real Hamiltonian of the supercell
    >>> ham.kernel()                             # FCI of the supercell (small cases)

Sum rule: the expectation value of H_act over the reference determinant is
E(KOBMP2) - E_c[T_act], with E_c[T_act] the correlation energy of the active
double excitations; it is available as :meth:`energy_tot` and is part of the
test suite, together with the limits of an empty and of a complete active
space and the molecular code at the Gamma point.

Divergence of the exchange.  With ``exxdiv='ewald'`` in the mean field, the
Madelung term of the active electrons, -xi nelecas / 2, is a constant of the
many-body Hamiltonian and is part of E_core; the two-electron integrals do
not contain it.  The Fock matrix of :meth:`get_fock` carries the usual shift
of the occupied levels, so that its eigenvalues are those of KRHF for a
complete active space.

Reference:
    N. T. Le and L. N. Tran, J. Phys. Chem. A 127, 5222 (2023)   (molecules)
'''

import numpy
import scipy.linalg
from pyscf import ao2mo, fci, gto, lib, scf
from pyscf.lib import logger
from pyscf.pbc import tools

from pycmf.core import mpi, status
from pycmf.pbc import kbch, kqp
from pycmf.pbc.kobmp2 import KOBMP2


class KOBDF(lib.StreamObject):
    '''Active-space Hamiltonian downfolded with the correlation potential of
    k-point OBMP2.

    Args:
        mp : :class:`pycmf.pbc.KOBMP2` object after ``kernel()`` (or after
            ``init_from_scf()``: second-order downfolding on Hartree-Fock
            orbitals)
        ncas : number of active bands per k-point
        nelecas : number of active electrons per unit cell (even)
        cas_list : indices (0-based, in the energy order of ``mp``) of the
            active bands, the same at every k-point.  By default the ``ncas``
            bands around the Fermi level that hold ``nelecas`` electrons.

    Attributes:
        fcisolver : solver of :meth:`kernel`, interface of :mod:`pyscf.fci`
        conv_tol, max_cycle : convergence of :meth:`scf`

    Saved results:
        e_core : constant of H_act per unit cell (with the nuclear repulsion)
        h1eff : effective one-body integrals, (nkpts, ncas, ncas)
        mo_coeff : active orbitals (AO basis), list over the k-points
        e_hf, mo_energy, mo_rot, mo_occ : mean field of H_act from :meth:`scf`:
            energy per cell, band energies (nkpts, ncas), orbitals in the basis
            of the active orbitals, occupations
        e_tot, e_cas, ci : results of :meth:`kernel`
    '''

    conv_tol = 1e-10
    max_cycle = 50

    _keys = {'cell', 'mol', 'mp', 'kpts', 'nkpts', 'ncas', 'nelecas', 'cas_list', 'ncore',
             'fcisolver', 'conv_tol', 'max_cycle', 'max_memory', 'e_core', 'h1eff',
             'mo_coeff', 'e_hf', 'mo_energy', 'mo_rot', 'mo_occ', 'converged', 'e_tot',
             'e_cas', 'ci', 'e_ref', 'e_corr_act'}

    def __init__(self, mp, ncas, nelecas, cas_list=None):
        status.experimental(self.__class__.__name__)
        if not isinstance(mp, KOBMP2):
            raise TypeError('KOBDF needs a KOBMP2 object.')
        if mp.mo_energy is None or mp._sym is None:
            raise RuntimeError('Run the KOBMP2 calculation (or init_from_scf()) first.')
        if nelecas % 2 or nelecas < 0:
            raise ValueError('nelecas must be an even number (closed shell).')
        self.mp = mp
        self.cell = self.mol = mp.cell
        self.kpts = mp.kpts
        self.nkpts = mp.nkpts
        self.verbose = mp.verbose
        self.stdout = mp.stdout
        self.max_memory = mp.max_memory
        self.ncas = int(ncas)
        self.nelecas = int(nelecas)
        self.cas_list = cas_list
        self.ncore = None
        self.fcisolver = fci.direct_spin1.FCI()

        self.e_core = None
        self.h1eff = None
        self.mo_coeff = None
        self.e_ref = None
        self.e_corr_act = None
        self.e_hf = None
        self.mo_energy = None
        self.mo_rot = None
        self.mo_occ = None
        self.converged = False
        self.e_tot = None
        self.e_cas = None
        self.ci = None
        self._ints = None
        self._cderi = {}
        self._se = None

    # ---- construction
    def _active_indices(self, nocc, nmo, mo_energy, log):
        '''Index arrays of the core and of the active orbitals per k-point.'''
        if len(set(nocc)) != 1:
            raise NotImplementedError('the number of occupied bands depends on the k-point')
        nocc0 = nocc[0]
        if self.cas_list is None:
            ncore = nocc0 - self.nelecas // 2
            if ncore < 0:
                raise ValueError('More active electrons than electrons.')
            act0 = numpy.arange(ncore, ncore + self.ncas)
        else:
            act0 = numpy.sort(numpy.asarray(self.cas_list, dtype=int))
        if len(act0) != self.ncas or len(set(act0.tolist())) != self.ncas:
            raise ValueError('cas_list must hold ncas distinct bands.')
        if act0.max(initial=-1) >= min(nmo):
            raise ValueError('The active bands exceed the number of orbitals (%d).' % min(nmo))
        if numpy.count_nonzero(act0 < nocc0) != self.nelecas // 2:
            raise ValueError('The active bands hold %d electrons, not nelecas = %d.'
                             % (2 * numpy.count_nonzero(act0 < nocc0), self.nelecas))
        core0 = numpy.setdiff1d(numpy.arange(nocc0), act0)
        for k, e in enumerate(mo_energy):
            inact = numpy.setdiff1d(numpy.arange(e.size), act0)
            if len(inact) and len(act0) and abs(e[act0, None] - e[inact]).min() < 1e-6:
                log.warn('KOBDF: an active band is degenerate with an inactive one at '
                         'k-point %d: the active space is not uniquely defined.', k)
                break
        nk = len(nocc)
        return [core0] * nk, [act0] * nk

    def build(self):
        '''Construct E_core, h1eff and the active orbitals.'''
        log = logger.new_logger(self)
        cput0 = (logger.process_clock(), logger.perf_counter())
        mp = self.mp
        mf = mp._scf
        sym = mp._sym
        nk = self.nkpts
        ibz = sym.ibz2bz
        mo_e = [numpy.asarray(mp.mo_energy[k]) for k in ibz]
        mo_c = [numpy.asarray(mp.mo_coeff[k]) for k in ibz]
        nocc_bz = [int(numpy.count_nonzero(numpy.asarray(o) > 0)) for o in mp.mo_occ]
        nocc = [nocc_bz[k] for k in ibz]

        # potential of all double excitations, at the orbitals of mp
        im = mp.build(mo_e, mo_c, nocc)
        mo_bz = sym.expand(mo_c)
        e_bz = sym.expand_scalar(mo_e)
        nmo_bz = [c.shape[1] for c in mo_bz]
        core, act = self._active_indices(nocc_bz, nmo_bz, e_bz, log)
        self.ncore = len(core[0])

        # potential of the double excitations within the active bands
        occ_all, vir_all = mp._active(nocc_bz, nmo_bz)
        occ_act = [numpy.intersect1d(o, a) for o, a in zip(occ_all, act)]
        vir_act = [numpy.intersect1d(v, a) for v, a in zip(vir_all, act)]
        ints = mp._ints
        nrows = len(set(mpi.split(range(nk))) | set(int(k) for k in ibz))
        ints.update(mo_bz, occ_act, vir_act, nrows, nocc_bz)
        s1e = mp._overlap()
        v_act, c0_act, _ = kbch.correlation_potential(
            ints, sym, mp._kconserv(), e_bz, mo_bz, s1e, im.fock_hf, occ_act, vir_act,
            mp.c_os, mp.c_ss, mp.level_shift, mp.bch_order, log)
        v_ext = sym.expand_matrix([v - va for v, va in zip(im.v, v_act)])
        ints._rows = {}
        ints._h5 = None
        mp._ints = None
        self._ints = ints
        self._cderi = {}

        # mean field of the core electrons
        h1e = mp._hcore()
        e_core = mf.energy_nuc() + im.c0 - c0_act
        if self.ncore:
            dm_core = numpy.asarray([2 * c[:, i].dot(c[:, i].conj().T) for c, i in zip(mo_bz, core)])
            vhf_core = numpy.asarray(mpi.root_call(mf.get_veff, self.cell, dm_core))
            e_core += float(mf.energy_elec(dm_core, h1e, vhf_core)[0].real)
            fock_core = h1e + vhf_core
        else:
            fock_core = h1e
        e_core += 2. / nk * sum(numpy.trace(v[numpy.ix_(i, i)]).real for v, i in zip(v_ext, core))
        if mf.exxdiv == 'ewald':
            e_core -= .5 * self._madelung() * self.nelecas

        self.mo_coeff = [c[:, a] for c, a in zip(mo_bz, act)]
        self.h1eff = numpy.asarray([c.conj().T.dot(f).dot(c) + v[numpy.ix_(a, a)]
                                    for c, f, v, a in zip(self.mo_coeff, fock_core, v_ext, act)])
        self.h1eff = .5 * (self.h1eff + self.h1eff.conj().transpose(0, 2, 1))
        self.e_core = float(e_core)
        # correlation energy of the active double excitations (sum rule)
        e_c_act = c0_act
        for i, k in enumerate(ibz):
            o = numpy.arange(nocc_bz[k])
            e_c_act += 2. * sym.star[i] / nk * numpy.trace(v_act[i][numpy.ix_(o, o)]).real
        self.e_corr_act = float(e_c_act)
        self.e_ref = float(im.e_tot)
        self.e_hf = self.mo_energy = self.mo_rot = self.mo_occ = self._se = None
        log.info('KOBDF: %d active bands with %d electrons, %d core bands, %d k-points',
                 self.ncas, self.nelecas, self.ncore, nk)
        log.info('E_core = %.15g   E(KOBMP2) = %.15g   E_c[T_act] = %.15g',
                 self.e_core, self.e_ref, self.e_corr_act)
        log.timer('KOBDF Hamiltonian', *cput0)
        return self

    def _madelung(self):
        return tools.madelung(self.cell, self.kpts)

    def get_h1eff(self):
        '''Effective one-body integrals (nkpts, ncas, ncas) and E_core.'''
        if self.h1eff is None:
            self.build()
        return self.h1eff, self.e_core

    # ---- two-electron integrals
    def get_cderi(self, k1, k2):
        '''Three-index integrals of the active orbitals, L^Q_tu(k1, k2):
        (t k1, u k2 | v k3, w k4) = sum_Q L^Q_tu(k1, k2) L^Q_vw(k3, k4).'''
        if self.h1eff is None:
            self.build()
        if (k1, k2) not in self._cderi:
            self._cderi[k1, k2] = self._ints.block(k1, k2, self.mo_coeff[k1], self.mo_coeff[k2])
        return self._cderi[k1, k2]

    def get_h2eff(self, k1=None, k2=None, k3=None):
        '''Active two-electron integrals divided by Nk, chemists' notation:
        the block (k1, k2, k3) with shape (ncas,)*4, or without arguments the
        array (nkpts, nkpts, nkpts, ncas, ncas, ncas, ncas).  The fourth
        k-point follows from momentum conservation.'''
        kconserv = self.mp._kconserv()
        nk, n = self.nkpts, self.ncas
        if k1 is not None:
            k4 = kconserv[k1, k2, k3]
            return kqp._contract(self.get_cderi(k1, k2), self.get_cderi(k3, k4)) / nk
        if nk**3 * n**4 * 16e-6 > self.max_memory:
            raise MemoryError('The active integrals of the whole mesh need %.0f MB; request '
                              'single blocks or use get_cderi().' % (nk**3 * n**4 * 16e-6))
        out = numpy.empty((nk, nk, nk, n, n, n, n), dtype=numpy.complex128)
        for a in range(nk):
            for b in range(nk):
                for c in range(nk):
                    out[a, b, c] = self.get_h2eff(a, b, c)
        return out

    # ---- mean field of the active-space Hamiltonian
    def get_jk(self, dm):
        '''Coulomb and exchange matrices of H_act for the density matrices
        ``dm`` (nkpts, ncas, ncas) in the basis of the active orbitals.'''
        nk, n = self.nkpts, self.ncas
        rho = 0.
        for k in range(nk):
            l = self.get_cderi(k, k)
            rho = rho + numpy.dot(l.reshape(-1, n * n), dm[k].T.ravel())
        rho = rho / nk
        vj = numpy.empty((nk, n, n), dtype=numpy.complex128)
        vk = numpy.zeros((nk, n, n), dtype=numpy.complex128)
        for k in range(nk):
            vj[k] = numpy.dot(rho, self.get_cderi(k, k).reshape(-1, n * n)).reshape(n, n)
            for kp in range(nk):
                x = numpy.dot(self.get_cderi(k, kp), dm[kp])                        # [Q,t,v]
                y = self.get_cderi(kp, k)                                           # [Q,v,u]
                vk[k] += numpy.dot(x.transpose(1, 0, 2).reshape(n, -1),
                                   y.reshape(-1, n))
        return vj, vk / nk

    def reference_rdm1(self):
        '''Density matrices of the reference determinant (the occupied active
        bands of mp) in the basis of the active orbitals.'''
        nk, n, no = self.nkpts, self.ncas, self.nelecas // 2
        dm = numpy.zeros((nk, n, n), dtype=numpy.complex128)
        dm[:, numpy.arange(no), numpy.arange(no)] = 2.
        return dm

    def make_rdm1(self, mo_rot=None):
        '''Density matrices of a closed-shell determinant of H_act in the
        basis of the active orbitals: for the orbitals ``mo_rot``, by default
        those of :meth:`scf` (the reference determinant before it is run).'''
        no = self.nelecas // 2
        if mo_rot is None:
            mo_rot = self.mo_rot
        if mo_rot is None:
            return self.reference_rdm1()
        return numpy.asarray([2 * u[:, :no].dot(u[:, :no].conj().T) for u in mo_rot])

    def get_fock(self, dm=None):
        '''Fock matrices of H_act, (nkpts, ncas, ncas).'''
        if dm is None:
            dm = self.make_rdm1()
        h1 = self.get_h1eff()[0]
        vj, vk = self.get_jk(dm)
        fock = h1 + vj - .5 * vk
        if self.mp._scf.exxdiv == 'ewald':
            fock = fock - .5 * self._madelung() * dm
        return fock

    def energy_tot(self, dm=None):
        '''Expectation value of H_act (per unit cell) over the determinant
        with the density matrices ``dm`` (default: :meth:`make_rdm1`).  For
        :meth:`reference_rdm1` it equals E(KOBMP2) - E_c[T_act].'''
        if dm is None:
            dm = self.make_rdm1()
        h1, e_core = self.get_h1eff()
        vj, vk = self.get_jk(dm)
        e = numpy.einsum('kij,kji->', h1 + .5 * (vj - .5 * vk), dm).real / self.nkpts
        return float(e_core + e)

    def scf(self, dm0=None):
        '''Closed-shell Hartree-Fock of H_act.  Sets ``e_hf``, ``mo_energy``,
        ``mo_rot``, ``mo_occ`` and returns the energy per unit cell.'''
        log = logger.new_logger(self)
        nk, n, no = self.nkpts, self.ncas, self.nelecas // 2
        dm = self.reference_rdm1() if dm0 is None else numpy.asarray(dm0)
        adiis = lib.diis.DIIS()
        adiis.space = 8
        e_last = self.energy_tot(dm)
        self.converged = False
        for cycle in range(self.max_cycle):
            fock = self.get_fock(dm)
            err = numpy.asarray([f.dot(d) - d.dot(f) for f, d in zip(fock, dm)])
            fock = adiis.update(fock, xerr=err)
            mo_energy = numpy.empty((nk, n))
            mo_rot = numpy.empty((nk, n, n), dtype=numpy.complex128)
            for k in range(nk):
                mo_energy[k], mo_rot[k] = scipy.linalg.eigh(fock[k])
            if no and no < n and mo_energy[:, no - 1].max() > mo_energy[:, no].min():
                log.warn('KOBDF.scf: the bands of H_act overlap (no gap); the occupations '
                         'are kept at %d bands per k-point.', no)
            dm = self.make_rdm1(mo_rot)
            e = self.energy_tot(dm)
            log.debug('KOBDF scf cycle %d  E = %.15g  delta_E = %.3g  |[F,D]| = %.3g',
                      cycle + 1, e, e - e_last, abs(err).max())
            if abs(e - e_last) < self.conv_tol and abs(err).max() < numpy.sqrt(self.conv_tol):
                self.converged = True
                break
            e_last = e
        # eigenvalues and orbitals of the Fock matrix of the final density
        fock = self.get_fock(dm)
        for k in range(nk):
            mo_energy[k], mo_rot[k] = scipy.linalg.eigh(fock[k])
        self.mo_energy, self.mo_rot = mo_energy, mo_rot
        self.mo_occ = numpy.zeros((nk, n))
        self.mo_occ[:, :no] = 2.
        self.e_hf = self.energy_tot(self.make_rdm1(mo_rot))
        self._se = None
        if not self.converged:
            log.warn('KOBDF.scf not converged in %d cycles', self.max_cycle)
        log.note('E(HF of H_act) = %.15g per cell', self.e_hf)
        return self.e_hf

    def band_gap(self):
        '''Gap of the mean-field bands of H_act on the k-mesh.'''
        if self.mo_energy is None:
            self.scf()
        no = self.nelecas // 2
        return self.mo_energy[:, no:].min() - self.mo_energy[:, :no].max()

    # ---- second-order quasiparticle energies of H_act
    def self_energy(self, nocc=None, nvir=None, kpts_index=None, grid=None, c_os=1., c_ss=1.):
        '''Diagonal second-order self-energy of H_act for the bands of
        :meth:`scf`, tabulated as in :func:`pycmf.pbc.kqp.self_energy`.

        The mean-field bands of H_act contain the correlation with the
        orbitals outside the active space through v_ext, statically; the
        self-energy adds the correlation within the active space with its
        frequency dependence (both the 2p1h and the 2h1p part).

        Args:
            nocc, nvir : numbers of highest occupied and lowest virtual active
                bands that are treated (default: all)
            kpts_index : k-points; default: the irreducible ones, copied to
                the symmetry-equivalent k-points
            grid : frequency offsets from the band energies (Hartree)
            c_os, c_ss : spin-component scaling of the self-energy

        The result is kept and used by :meth:`quasiparticle`.
        '''
        log = logger.new_logger(self)
        cput0 = (logger.process_clock(), logger.perf_counter())
        if self.mo_energy is None:
            self.scf()
        nk, n, no = self.nkpts, self.ncas, self.nelecas // 2
        nv = n - no
        if no == 0 or nv == 0:
            raise ValueError('the active space has no occupied or no virtual band')
        sym = self.mp._sym
        kconserv = self.mp._kconserv()
        u = self.mo_rot
        cache = {}

        def cderi(k1, k2):
            if (k1, k2) not in cache:
                l = self.get_cderi(k1, k2)
                l = numpy.dot(l, u[k2])
                cache[k1, k2] = lib.einsum('ti,Qtu->Qiu', u[k1].conj(), l)
            return cache[k1, k2]

        e_o = [self.mo_energy[k, :no] for k in range(nk)]
        e_v = [self.mo_energy[k, no:] for k in range(nk)]
        gap0 = self.band_gap()
        if grid is None:
            half = min(.4, 1.4 * gap0)
            grid = numpy.linspace(-half, half, 41)
        grid = numpy.asarray(grid, dtype=float)
        i0 = int(numpy.argmin(abs(grid)))
        if abs(grid[i0]) > 1e-12:
            raise ValueError('the frequency grid must contain 0')
        n_h = no if nocc is None else min(nocc, no)
        n_l = nv if nvir is None else min(nvir, nv)
        bands = numpy.arange(no - n_h, no + n_l)
        is_occ = bands < no
        alpha, beta = .5 * (c_ss + c_os), .5 * c_ss
        targets = [int(k) for k in (sym.ibz2bz if kpts_index is None else kpts_index)]
        out = [None] * nk
        for kt in targets:
            e_p = self.mo_energy[kt, bands]
            l_pv = [cderi(kt, kb)[:, bands][:, :, no:] for kb in range(nk)]
            l_op = [cderi(kj, kt)[:, :no][:, :, bands] for kj in range(nk)]
            a, b, da, db = kqp.tabulate(kt, e_p, grid, kconserv, e_o, e_v,
                                        lambda ki, ka: cderi(ki, ka)[:, :no, no:],
                                        l_pv, l_op, alpha, beta)
            out[kt] = {'occ': is_occ, 'e': e_p, 'grid': grid, 'A': a, 'B': b,
                       'A0': a[:, i0].copy(), 'B0': b[:, i0].copy(), 'dA': da, 'dB': db,
                       'gap': gap0}
        if kpts_index is None:
            for k, i in enumerate(sym.bz2ibz):
                out[k] = out[sym.ibz2bz[i]]
        self._se = out
        log.timer('second-order self-energy of H_act', *cput0)
        return out

    def quasiparticle(self, scheme='dynamic'):
        '''Quasiparticle energies of the bands treated by :meth:`self_energy`:
        'static' e + Sigma(e), 'linear' e + Z Sigma(e), or 'dynamic' (root of
        w = e + Sigma(w)).  Returns (energies, Z), lists over the k-points.'''
        if self._se is None:
            self.self_energy()
        return kqp.quasiparticle(self._se, scheme, 'hf')

    def quasiparticle_gap(self, scheme='dynamic'):
        '''(direct gap at the first k-point, smallest gap on the mesh).'''
        e_qp, _ = self.quasiparticle(scheme)
        se = [s for s in self._se if s is not None]
        return kqp.gaps(se, [e for e in e_qp if e is not None])[:2]

    # ---- many-body solvers: Hamiltonian of the supercell
    def _real_rotation(self, tol=1e-6):
        '''Unitary matrix W, (nkpts*ncas, nkpts*ncas), from the active Bloch
        orbitals (k, t) to real orbitals of the Born-von Karman supercell.

        Complex conjugation maps the active orbitals of k on those of -k,
        conj(psi_k) = psi_{-k} T(k).  The matrix T of all k-points is unitary
        and symmetric, T = V V^T, and W = V makes psi W real.
        '''
        nk, n = self.nkpts, self.ncas
        s1e = self.mp._overlap()
        ks = self.cell.get_scaled_kpts(self.kpts)
        t = numpy.zeros((nk * n, nk * n), dtype=numpy.complex128)
        for k in range(nk):
            d = ks + ks[k]
            d -= numpy.rint(d)
            mk = int(numpy.argmin(abs(d).sum(axis=1)))
            if abs(d[mk]).max() > 1e-8:
                raise ValueError('the k-mesh does not contain -k for every k')
            c, cm = self.mo_coeff[k], self.mo_coeff[mk]
            t[mk * n:(mk + 1) * n, k * n:(k + 1) * n] = cm.conj().T.dot(s1e[mk]).dot(c.conj())
        if abs(t.dot(t.conj().T) - numpy.eye(nk * n)).max() > tol:
            raise ValueError('The active space is not invariant under time reversal: no real '
                             'supercell orbitals (deviation %.2g).'
                             % abs(t.dot(t.conj().T) - numpy.eye(nk * n)).max())
        # square root of the unitary matrix as a function of the matrix, with
        # the branch cut in the largest gap of the eigenphases
        w, v = scipy.linalg.schur(t, output='complex')
        theta = numpy.angle(numpy.diag(w))
        srt = numpy.sort(theta)
        gaps = numpy.append(srt[1:] - srt[:-1], srt[0] + 2 * numpy.pi - srt[-1])
        i = int(numpy.argmax(gaps))
        cut = srt[i] + .5 * gaps[i]
        theta = numpy.mod(theta - cut, 2 * numpy.pi) + cut
        return (v * numpy.exp(.5j * theta)).dot(v.conj().T)

    def supercell(self, tol=1e-6):
        '''Hamiltonian of the Born-von Karman supercell (Nk unit cells) in
        real orthonormal orbitals, for many-body solvers.

        Returns:
            h1 : (N, N) real, N = nkpts * ncas
            h2 : (N, N, N, N) real, chemists' notation
            e0 : constant, nkpts * E_core
            nelec : number of electrons, nkpts * nelecas

        Energies of the supercell are Nk times the energies per unit cell.
        The orbitals are an arbitrary real unitary combination of the active
        Bloch orbitals (not localized); ``_real_rotation()`` returns it.
        '''
        nk, n = self.nkpts, self.ncas
        ntot = nk * n
        if ntot**4 * 8e-6 * 2 > self.max_memory:
            raise MemoryError('supercell integrals need %.0f MB' % (ntot**4 * 16e-6))
        h1k, e_core = self.get_h1eff()
        w = self._real_rotation(tol)
        wk = [w[k * n:(k + 1) * n] for k in range(nk)]
        h1 = sum(wk[k].conj().T.dot(h1k[k]).dot(wk[k]) for k in range(nk))
        kconserv = self.mp._kconserv()
        h2 = numpy.zeros((ntot, ntot, ntot, ntot), dtype=numpy.complex128)
        for label in range(nk):
            # pairs (k1, k2) with k1 - k2 = q, and pairs (k3, k4) with k4 - k3 = q
            left = right = 0.
            for k1 in range(nk):
                for k2 in range(nk):
                    if kconserv[k1, k2, 0] == label:
                        l = self.get_cderi(k1, k2)
                        left = left + lib.einsum('ta,Qtu,ub->Qab', wk[k1].conj(), l, wk[k2])
                    if kconserv[k2, k1, 0] == label:
                        l = self.get_cderi(k1, k2)
                        right = right + lib.einsum('ta,Qtu,ub->Qab', wk[k1].conj(), l, wk[k2])
            h2 += numpy.dot(left.reshape(-1, ntot * ntot).T,
                            right.reshape(-1, ntot * ntot)).reshape((ntot,) * 4)
        h2 /= nk
        err = max(abs(h1.imag).max(), abs(h2.imag).max())
        if err > tol:
            raise RuntimeError('The supercell Hamiltonian is not real (%.2g).' % err)
        logger.debug(self, 'supercell Hamiltonian: %d orbitals, imaginary part %.2g', ntot, err)
        return h1.real, h2.real, nk * e_core, nk * self.nelecas

    def as_scf(self):
        '''Restricted Hartree-Fock object of PySCF for the supercell
        Hamiltonian (not converged), to be used with the molecular
        post-Hartree-Fock solvers, e.g. ``cc.CCSD(ham.as_scf().run())``.
        Its energies refer to the supercell.'''
        h1, h2, e0, nelec = self.supercell()
        ntot = h1.shape[0]
        mol = gto.M(verbose=0)
        mol.nelectron = nelec
        mol.incore_anyway = True
        mf = scf.RHF(mol)
        mf.get_hcore = lambda *args: h1
        mf.get_ovlp = lambda *args: numpy.eye(ntot)
        mf.energy_nuc = lambda *args: e0
        mf._eri = ao2mo.restore(8, h2, ntot)
        mf.init_guess = '1e'
        return mf

    def kernel(self, ci0=None, **kwargs):
        '''Solve H_act on the supercell with ``fcisolver`` and return the
        total energy per unit cell.  Only for small models (nkpts * ncas
        orbitals in the solver).'''
        h1, h2, e0, nelec = self.supercell()
        ntot = h1.shape[0]
        e, self.ci = self.fcisolver.kernel(h1, h2, ntot, (nelec // 2, nelec // 2),
                                           ci0=ci0, **kwargs)
        self.e_cas = numpy.asarray(e) / self.nkpts
        self.e_tot = self.e_cas + self.e_core
        if numpy.ndim(e) == 0:
            self.e_cas, self.e_tot = float(self.e_cas), float(self.e_tot)
        logger.note(self, 'E(KOBDF) = %s  E_cas = %s  E_core = %.15g  (per cell)',
                    self.e_tot, self.e_cas, self.e_core)
        return self.e_tot
